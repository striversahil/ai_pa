#!/usr/bin/env python3
"""Regenerate docs/REUSABLE_COMPONENTS.md: every file added by the split refactor
(since BASE) with its exported components / functions / types.
Usage: python3 scripts/refactor/gen-reusable-catalog.py [BASE=36c652d]"""
import subprocess, re, os, sys
BASE = sys.argv[1] if len(sys.argv) > 1 else '36c652d'
added = subprocess.check_output(['git', 'diff', '--name-only', '--diff-filter=A', BASE, 'HEAD'], text=True).split()
added += subprocess.check_output(['git', 'ls-files', '--others', '--exclude-standard'], text=True).split()
added = sorted({f for f in added if os.path.exists(f) and re.search(r'/src/.*\.(ts|tsx)$', f)
                and ('-parts/' in f or re.search(r'components/[a-z0-9-]+/|crm/order-panel/', f)) and 'workspaces' not in f})
fe = [f for f in added if f.startswith('founder-os_frontend')]
be = [f for f in added if f.startswith('founder-os_backend')]
def exports(f):
    s = open(f).read()
    return [(m.group(1), m.group(2)) for m in re.finditer(r'^export (?:async )?(function|const|class|interface|type|enum)\s+(\w+)', s, re.M)]
L = ["# Reusable building blocks (generated by scripts/refactor/gen-reusable-catalog.py)", "",
     "Everything below was split out of an oversized file by `scripts/refactor/split-module.mjs` and is importable on its own. "
     "The original files still re-export every name they exported before, so existing imports keep working.", "",
     "Conventions: frontend `<Name>.tsx` = one component, `helpers.ts` = non-UI helpers, `types.ts` = types. "
     "Backend `pure.ts` = synchronous logic with **no** DB/cache/network/async (safe to reuse anywhere, including tests), "
     "`io.ts` = everything that does I/O, `types.ts` = types. `pure.ts` never imports `io.ts`.", "",
     "Shared kits: `@/components/ui` (Badge, Card, KpiCard, Skeleton, EmptyState/ErrorState, Table, TabBar, Modal, ConfirmDialog, Popover) · "
     "`@/lib/format` (money/date formatters) · `@/workspaces` (WorkspaceRenderer, workspaceDataUrl, useWorkspaces, useWorkspaceHost) · "
     "backend `worker/viewer.ts` (getViewer/getViewerMe), `worker/http.ts` (readBody), `modules/workspaces/` (catalog, scoping, getWorkspaceData).", ""]
for title, lst, strip in [("Frontend", fe, 'founder-os_frontend/src/'), ("Backend", be, 'founder-os_backend/src/')]:
    L += [f"## {title} ({len(lst)} files)"]
    cur = None
    for f in lst:
        d = os.path.dirname(f).replace(strip, '')
        if d != cur:
            L += ["", f"### `{d}/`"]; cur = d
        ex = exports(f)
        comps = [n for k, n in ex if k in ('function', 'const', 'class') and n[:1].isupper() and f.endswith('.tsx')]
        vals = [n for k, n in ex if k in ('function', 'const', 'class', 'enum') and n not in comps]
        types = [n for k, n in ex if k in ('interface', 'type')]
        parts = []
        if comps: parts.append("components: " + ", ".join(f"`{n}`" for n in comps))
        if vals: parts.append("functions/values: " + ", ".join(f"`{n}`" for n in vals))
        if types: parts.append("types: " + ", ".join(f"`{n}`" for n in types))
        L.append(f"- `{os.path.basename(f)}` — " + ("; ".join(parts) or "—"))
    L.append("")
open('docs/REUSABLE_COMPONENTS.md', 'w').write("\n".join(L) + "\n")
print(f"catalog: {len(fe)} frontend + {len(be)} backend files")
