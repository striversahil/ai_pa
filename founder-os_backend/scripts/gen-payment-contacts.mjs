/**
 * Generate the Payment Tracker client-contact data migration from
 * `client_contact.json` (repo root).
 *
 * Run: node scripts/gen-payment-contacts.mjs [--out migrations/NNNN_*.sql] [--json path]
 *
 * The generated migration:
 *   - overwrites non-empty phone/email/region on matched PaymentCustomer rows
 *   - stamps region on every DebtorInvoice row for that normalized customer
 *     (including soft-deleted rows, so a restore keeps the region)
 *   - never deletes contacts or clears a field that is null in the JSON
 *
 * Re-run after updating the JSON, with a fresh --out path (migrations are
 * immutable). The script refuses to overwrite an existing file unless --force.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const opt = (name, fallback = '') => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};

const jsonPath = resolve(opt('--json', join(root, '..', 'client_contact.json')));
const outPath = resolve(opt('--out', join(root, 'migrations', '0076_payment_tracker_client_contacts.sql')));
if (existsSync(outPath) && !flag('--force')) {
  throw new Error(`${outPath} already exists — pass --out <new-migration.sql> (or --force to overwrite)`);
}

const src = JSON.parse(readFileSync(jsonPath, 'utf8'));
if (!src || typeof src !== 'object' || Array.isArray(src)) {
  throw new Error('client_contact.json must be an object keyed by customer name');
}

const REGIONS = new Set(['R1', 'R2', 'R3', 'R4']);
const normName = (v) => String(v ?? '').replace(/\s+/g, ' ').trim();
const keyOf = (v) => normName(v).toLowerCase();
const sql = (v) => `'${String(v ?? '').replace(/'/g, "''")}'`;

function normalizePhone(raw) {
  const digits = String(raw ?? '').replace(/[^\d]/g, '');
  if (!digits) return '';
  if (digits.length === 10 && /^[6-9]/.test(digits)) return `91${digits}`;
  if (digits.length === 11 && digits.startsWith('0')) return `91${digits.slice(1)}`;
  return digits;
}
const validPhone = (v) => v === '' || (v.length >= 8 && v.length <= 15);
const validEmail = (v) => /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(v);

const entries = [];
const byKey = new Map();
const invalid = [];
const skipped = [];

for (const [name, raw] of Object.entries(src)) {
  const customerName = normName(name);
  const key = keyOf(customerName);
  if (!key) { skipped.push({ name, reason: 'blank customer name' }); continue; }
  if (byKey.has(key)) { skipped.push({ name, reason: `duplicate normalized key (${byKey.get(key).name})` }); continue; }

  const phone = normalizePhone(raw?.phone);
  const email = String(raw?.email ?? '').trim();
  const region = String(raw?.region ?? '').trim().toUpperCase();

  if (phone && !validPhone(phone)) invalid.push({ name, field: 'phone', value: raw?.phone });
  if (email && !validEmail(email)) invalid.push({ name, field: 'email', value: raw?.email });
  if (region && !REGIONS.has(region)) invalid.push({ name, field: 'region', value: raw?.region });

  const entry = {
    name: customerName,
    key,
    phone: validPhone(phone) ? phone : '',
    email: validEmail(email) ? email.slice(0, 320) : '',
    region: REGIONS.has(region) ? region : '',
  };
  entries.push(entry);
  byKey.set(key, entry);
}

/**
 * Known name variants that resolve to one source contact. We only borrow the
 * region for the alias row — never its phone/email — so the separate contact
 * row does not become a second reminder target.
 */
const REGION_ALIASES = {
  'arya manufacturing co.(delhi)': 'arya manufacturing co.(delhi) dr.',
};

const lines = [];
lines.push('-- Payment Tracker: client contact + region sync from client_contact.json.');
lines.push('-- GENERATED by scripts/gen-payment-contacts.mjs — do not hand-edit.');
lines.push(`-- Source: ${relative(root, jsonPath)}`);
lines.push(`-- Entries: ${entries.length} · phone: ${entries.filter((e) => e.phone).length} · email: ${entries.filter((e) => e.email).length} · region: ${entries.filter((e) => e.region).length}`);
lines.push('-- Blank/null JSON fields are left untouched, never cleared.');
lines.push('');

for (const e of entries) {
  const sets = [];
  if (e.phone) sets.push(`"phone" = ${sql(e.phone)}`);
  if (e.email) sets.push(`"email" = ${sql(e.email)}`);
  if (e.region) sets.push(`"region" = ${sql(e.region)}`);
  if (sets.length) {
    lines.push(`UPDATE "PaymentCustomer" SET ${sets.join(', ')}, "updatedBy" = 'client_contact.json', "updatedAt" = datetime('now') WHERE "customerKey" = ${sql(e.key)};`);
  }
  if (e.region) {
    lines.push(`UPDATE "DebtorInvoice" SET "region" = ${sql(e.region)}, "updatedAt" = datetime('now') WHERE lower(trim("customerName")) = ${sql(e.key)};`);
  }
}

const aliasReport = [];
for (const [aliasKey, sourceKey] of Object.entries(REGION_ALIASES)) {
  const source = byKey.get(sourceKey);
  if (!source?.region) { aliasReport.push({ aliasKey, sourceKey, applied: false, reason: 'source has no region' }); continue; }
  lines.push(`-- Alias: ${aliasKey} → ${sourceKey} (region only; contact phone/email stay separate)`);
  lines.push(`UPDATE "PaymentCustomer" SET "region" = ${sql(source.region)}, "updatedBy" = 'client_contact.json', "updatedAt" = datetime('now') WHERE "customerKey" = ${sql(aliasKey)};`);
  lines.push(`UPDATE "DebtorInvoice" SET "region" = ${sql(source.region)}, "updatedAt" = datetime('now') WHERE lower(trim("customerName")) = ${sql(aliasKey)};`);
  aliasReport.push({ aliasKey, sourceKey, applied: true, region: source.region });
}

lines.push('');
writeFileSync(outPath, lines.join('\n'));

console.log(JSON.stringify({
  jsonPath,
  outPath,
  entries: entries.length,
  phones: entries.filter((e) => e.phone).length,
  emails: entries.filter((e) => e.email).length,
  regions: entries.filter((e) => e.region).length,
  noRegion: entries.filter((e) => !e.region).map((e) => e.name),
  invalid,
  skipped,
  aliases: aliasReport,
}, null, 2));
