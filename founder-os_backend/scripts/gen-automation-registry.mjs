#!/usr/bin/env node
/**
 * gen-automation-registry.mjs — build-time auto-discovery of automations.
 *
 * Scans src/automations/* (skipping `_template` and dot-dirs), reads each
 * automation's rule.json (falling back to a sensible default when missing),
 * detects whether it exports a dashboard `data` provider, and GENERATES:
 *
 *   src/modules/automation/registry.generated.ts  — MODULES + RULES + DASHBOARD_SLUGS
 *   ../../founder-os_frontend/src/automation-manifest.generated.ts — slug→scope map
 *   (the dashboard slugs + their permission scopes, so the frontend's
 *   VIEW_SCOPE / DASHBOARD_SCOPES never go stale)
 *
 * So adding a new automation directory needs NO manual registry edits — the
 * next `npm run build` / `build-worker.mjs` picks it up automatically.
 *
 * Usage:
 *   node scripts/gen-automation-registry.mjs   # regenerate (idempotent)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const AUTOMATIONS_DIR = path.join(root, 'src/automations');
const OUT_FILE = path.join(root, 'src/modules/automation/registry.generated.ts');
const FE_OUT_FILE = path.join(root, '../founder-os_frontend/src/automation-manifest.generated.ts');

const TRIGGER_DEFAULTS = {
  type: 'schedule',
  cron: '* * * * *',
};

function readRuleFile(dir) {
  const rulePath = path.join(dir, 'rule.json');
  if (!fs.existsSync(rulePath)) return null;
  try {
    return JSON.parse(fs.readFileSync(rulePath, 'utf8'));
  } catch (e) {
    console.warn(`gen-automation-registry: invalid rule.json in ${path.basename(dir)} — ${e.message}`);
    return null;
  }
}

/** Detect a dashboard `data` provider in index.ts (regex scan — build-time only). */
function exportsData(dir) {
  const indexPath = path.join(dir, 'index.ts');
  if (!fs.existsSync(indexPath)) return false;
  const src = fs.readFileSync(indexPath, 'utf8');
  // export function data / export async function data / export { foo as data }
  return /\bexport\s+(?:async\s+)?function\s+data\b/.test(src) ||
    /\bexport\s*\{[^}]*\bas\s+data\b/.test(src);
}

function toIdentifier(slug) {
  const camel = slug.replace(/[-_]+(\w)/g, (_, c) => c.toUpperCase());
  return camel.replace(/^(\w)/, (c) => c.toLowerCase());
}

function collect() {
  let dirs = [];
  try {
    dirs = fs.readdirSync(AUTOMATIONS_DIR, { withFileTypes: true })
      .filter((d) => d.isDirectory() && !d.name.startsWith('_') && !d.name.startsWith('.'))
      .map((d) => d.name)
      .sort();
  } catch (e) {
    console.error('gen-automation-registry: automations dir not found', e.message);
    return { entries: [], dashboards: [] };
  }

  const entries = [];
  const dashboards = [];
  for (const slug of dirs) {
    const dir = path.join(AUTOMATIONS_DIR, slug);
    const hasIndex = fs.existsSync(path.join(dir, 'index.ts'));
    const rule = readRuleFile(dir);
    const hasData = exportsData(dir);

    entries.push({
      slug,
      hasIndex,
      hasData,
      name: rule?.name ?? slug,
      description: rule?.description ?? null,
      type: rule?.type ?? 'handler',
      trigger: rule?.trigger ?? TRIGGER_DEFAULTS,
      condition: rule?.condition ?? null,
      dedupField: rule?.dedupField ?? null,
      actions: rule?.actions ?? [],
      config: rule?.config ?? {},
      cooldownMs: rule?.cooldownMs ?? 0,
      enabled: rule?.enabled ?? true,
      // Optional permission scope for the dashboard (rule.json `scope` field).
      // Convention fallback: an explicit map is NOT required — the frontend
      // treats any dashboard without a declared scope as `automations`.
      scope: rule?.scope ?? null,
    });
    if (hasData) dashboards.push(slug);
  }
  return { entries, dashboards };
}

function render(entries, dashboards) {
  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/gen-automation-registry.mjs — DO NOT EDIT.');
  lines.push('// Regenerate with `node scripts/gen-automation-registry.mjs` (runs automatically');
  lines.push('// inside build-worker.mjs / npm run build). Adding an automation directory under');
  lines.push('// src/automations/<slug>/ is picked up automatically on the next build.');
  lines.push('//');
  lines.push('// eslint-disable-next-line @typescript-eslint/no-explicit-any');
  lines.push('// @ts-nocheck');
  lines.push('');

  // Static imports so esbuild bundles every automation into the Worker.
  for (const e of entries) {
    if (!e.hasIndex) continue;
    lines.push(`import * as ${toIdentifier(e.slug)} from '../../automations/${e.slug}';`);
  }
  lines.push('');

  lines.push('export interface GeneratedAutomationMeta {');
  lines.push('  slug: string;');
  lines.push('  name: string;');
  lines.push('  description: string | null;');
  lines.push('  type: string;');
  lines.push('  trigger: any;');
  lines.push('  condition: any;');
  lines.push('  dedupField: string | null;');
  lines.push('  actions: any[];');
  lines.push('  config: any;');
  lines.push('  cooldownMs: number;');
  lines.push('  enabled: boolean;');
  lines.push('  scope: string | null;');
  lines.push('}');
  lines.push('');

  lines.push('export const AUTOMATION_MODULES: Record<string, any> = {');
  for (const e of entries) {
    if (e.hasIndex) lines.push(`  '${e.slug}': ${toIdentifier(e.slug)},`);
  }
  lines.push('};');
  lines.push('');

  lines.push('export const AUTOMATION_RULES: Record<string, GeneratedAutomationMeta> = {');
  for (const e of entries) {
    lines.push(`  '${e.slug}': {`);
    lines.push(`    slug: '${e.slug}',`);
    lines.push(`    name: ${JSON.stringify(e.name)},`);
    lines.push(`    description: ${JSON.stringify(e.description)},`);
    lines.push(`    type: ${JSON.stringify(e.type)},`);
    lines.push(`    trigger: ${JSON.stringify(e.trigger)},`);
    lines.push(`    condition: ${JSON.stringify(e.condition)},`);
    lines.push(`    dedupField: ${JSON.stringify(e.dedupField)},`);
    lines.push(`    actions: ${JSON.stringify(e.actions)},`);
    lines.push(`    config: ${JSON.stringify(e.config)},`);
    lines.push(`    cooldownMs: ${e.cooldownMs},`);
    lines.push(`    enabled: ${e.enabled},`);
    lines.push(`    scope: ${JSON.stringify(e.scope)},`);
    lines.push('  },');
  }
  lines.push('};');
  lines.push('');

  lines.push('export const AUTOMATION_DASHBOARDS: string[] = [');
  for (const slug of dashboards) lines.push(`  '${slug}',`);
  lines.push('];');
  lines.push('');
  return lines.join('\n');
}

const { entries, dashboards } = collect();
const output = render(entries, dashboards);
fs.writeFileSync(OUT_FILE, output);
console.log(`gen-automation-registry: ${entries.length} automations, ${dashboards.length} dashboards → ${path.relative(root, OUT_FILE)}`);

// ── Frontend manifest: slug → scope so permissions never go stale ───────────
// Emits the dashboard slugs with their declared scope (rule.json `scope`) into
// the frontend so VIEW_SCOPE / DASHBOARD_SCOPES are derived, not hand-synced.
function renderFrontendManifest(entries, dashboards) {
  const lines = [];
  lines.push('// AUTO-GENERATED by founder-os_backend/scripts/gen-automation-registry.mjs — DO NOT EDIT.');
  lines.push('// Regenerate by running the backend build (build-worker.mjs) or');
  lines.push('// `node founder-os_backend/scripts/gen-automation-registry.mjs`.');
  lines.push('// eslint-disable-next-line @typescript-eslint/no-explicit-any');
  lines.push('// @ts-nocheck');
  lines.push('');
  lines.push('// slug → permission scope for each automation dashboard.');
  lines.push('// A dashboard without a declared scope (rule.json `scope`) maps to "automations".');
  lines.push('export const DASHBOARD_SCOPE_MAP: Record<string, string> = {');
  for (const slug of dashboards) {
    const entry = entries.find((e) => e.slug === slug);
    lines.push(`  '${slug}': ${JSON.stringify(entry?.scope ?? 'automations')},`);
  }
  lines.push('};');
  lines.push('');
  lines.push('export const AUTOMATION_DASHBOARDS: string[] = [');
  for (const slug of dashboards) lines.push(`  '${slug}',`);
  lines.push('];');
  lines.push('');
  return lines.join('\n');
}

try {
  const feManifest = renderFrontendManifest(entries, dashboards);
  fs.writeFileSync(FE_OUT_FILE, feManifest);
  console.log(`gen-automation-registry: frontend manifest → ${path.relative(root, FE_OUT_FILE)}`);
} catch (e) {
  console.warn('gen-automation-registry: frontend manifest write failed (frontend may not be present):', e.message);
}