// build-stock-backfill.mjs — converts stock_update.json (repo root) into the
// canonical backfill payload for POST /api/stock/backfill + a deterministic
// seed SQL applied via `wrangler d1 execute` (no session auth needed).
// Mirrors scripts/build-lead-import.mjs conventions.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = join(root, 'stock_update.json');
const raw = JSON.parse(readFileSync(src, 'utf8'));

const category = String(raw.category ?? 'Bolting Cloth');
const brand = String(raw.product_name ?? '').replace(/SEFAR\s*/i, '').trim() || 'SEFAR NYTAL';
const unit = String(raw.unit ?? 'meters').replace(/\s*\(assumed\)\s*/i, '').trim() || 'meters';
const planning = {
  leadTimeDays: Number(raw.lead_time_days) || 60,
  safetyFactor: Number(raw.safety_factor) || 5,
  moq: Number(raw.moq) || 25,
  source: 'stock_update.json',
};

const seen = new Set();
const items = [];
for (const r of raw.items_with_pending_stock ?? []) {
  const name = String(r.item ?? '').trim();
  if (!name || seen.has(name.toLowerCase())) continue;
  seen.add(name.toLowerCase());
  const max = Number(r.max_level) || 0;
  items.push({
    productName: name, category, brand, unit,
    supplier: String(raw.product_name ?? ''),
    avgDailyConsumption: Number(r.avg_daily_consumption) || 0,
    maxLevel: max, reorderLevel: max,
    leadTimeDays: planning.leadTimeDays, safetyFactor: planning.safetyFactor, moq: planning.moq,
  });
}
for (const name of raw.items_zero_consumption_pending_0 ?? []) {
  const n = String(name ?? '').trim();
  if (!n || seen.has(n.toLowerCase())) continue;
  seen.add(n.toLowerCase());
  items.push({
    productName: n, category, brand, unit,
    supplier: String(raw.product_name ?? ''),
    avgDailyConsumption: 0, maxLevel: 0, reorderLevel: 0,
    leadTimeDays: planning.leadTimeDays, safetyFactor: planning.safetyFactor, moq: planning.moq,
  });
}

const payload = { planning, items, summary: raw.summary ?? null };
const outPayload = join(root, 'founder-os_backend', 'scripts', 'stock-backfill.payload.json');
writeFileSync(outPayload, JSON.stringify(payload, null, 1));
console.log(`payload: ${items.length} items -> ${outPayload}`);

// Deterministic seed SQL: BOL-0001.. in file order, ids stk-bol-0001...
const esc = (s) => String(s ?? '').replace(/'/g, "''");
let sql = `-- SEFAR backfill seed (generated by scripts/build-stock-backfill.mjs — do not hand-edit).\n`;
items.forEach((it, i) => {
  const n = String(i + 1).padStart(4, '0');
  const sku = `BOL-${n}`;
  const id = `stk-bol-${n}`;
  sql += `INSERT INTO StockItem (id, sku, productName, category, brand, barcode, unit, unitPurchase, unitFactor, purchaseRate, saleRate, supplier, reorderLevel, minLevel, maxLevel, avgDailyConsumption, leadTimeDays, safetyFactor, moq, imageUrl, active, createdAt, updatedAt)\nVALUES ('${id}', '${sku}', '${esc(it.productName)}', '${esc(it.category)}', '${esc(it.brand)}', '', '${esc(it.unit)}', '', 1, 0, 0, '${esc(it.supplier)}', ${it.reorderLevel}, 0, ${it.maxLevel}, ${it.avgDailyConsumption}, ${it.leadTimeDays}, ${it.safetyFactor}, ${it.moq}, '', 1, datetime('now'), datetime('now'))\nON CONFLICT(sku) DO UPDATE SET productName=excluded.productName, category=excluded.category, brand=excluded.brand, unit=excluded.unit, supplier=excluded.supplier, reorderLevel=excluded.reorderLevel, maxLevel=excluded.maxLevel, avgDailyConsumption=excluded.avgDailyConsumption, leadTimeDays=excluded.leadTimeDays, safetyFactor=excluded.safetyFactor, moq=excluded.moq, active=1, updatedAt=datetime('now');\n`;
});
sql += `INSERT INTO Setting (key, value, updatedAt) VALUES ('stock:planning', '${esc(JSON.stringify(planning))}', datetime('now'))\nON CONFLICT(key) DO UPDATE SET value=excluded.value, updatedAt=datetime('now');\nINSERT INTO Setting (key, value, updatedAt) VALUES ('stock:seq:BOL', '${items.length}', datetime('now'))\nON CONFLICT(key) DO UPDATE SET value=excluded.value, updatedAt=datetime('now');\n`;
const outSql = join(root, 'founder-os_backend', 'scripts', 'stock-backfill.seed.sql');
writeFileSync(outSql, sql);
console.log(`seed SQL: ${items.length} upserts -> ${outSql}`);
